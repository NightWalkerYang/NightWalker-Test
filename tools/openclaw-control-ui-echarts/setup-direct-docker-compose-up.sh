    volumes:
      - ${OPENCLAW_CONFIG_DIR}:/home/node/.openclaw
      - ./tools/openclaw-control-ui-echarts/sidecar:/app/tools/openclaw-control-ui-echarts/sidecar:ro
    command:
      [
        "node",
        "tools/openclaw-control-ui-echarts/sidecar/tenant-platform/server.mjs"
