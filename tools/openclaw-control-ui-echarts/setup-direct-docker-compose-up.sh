resolve_source_dir() {
  local mode="${1:-auto}"

  if [[ "$mode" != "image-only" ]] && [[ -f "$ROOT_DIR/dist/control-ui/index.html" ]]; then
    printf '%s\n' "$ROOT_DIR/dist/control-ui"
    return 0
  fi

  command -v docker >/dev/null 2>&1 || fail "docker is required when dist/control-ui is not present on the host."

  printf '%s\n' "Host dist/control-ui is missing; extracting it from the Docker image..." >&2

  local image_ref
  image_ref="$(resolve_gateway_image_ref)"
  ensure_gateway_image_available "$image_ref"

  local extracted_dir="$tmp_dir/source-control-ui"
  mkdir -p "$extracted_dir"

  container_id="$(docker create "$image_ref")"
  docker cp "$container_id:/app/dist/control-ui/." "$extracted_dir"
  docker rm -f "$container_id" >/dev/null 2>&1 || true
  container_id=""

  [[ -f "$extracted_dir/index.html" ]] || fail "The Docker image does not contain /app/dist/control-ui/index.html"
  printf '%s\n' "$extracted_dir"
}

main() {
  require_file "$TOOL_DIR/build-custom-control-ui.mjs" "Custom Control UI builder"

  local source_dir=""
  local source_dir_mode=""
  local compose_up_applied="0"
  local image_ref=""
  local gateway_image_ready="0"
  image_ref="$(resolve_gateway_image_ref)"
  if host_control_ui_matches_current_checkout; then
    source_dir="$ROOT_DIR/dist/control-ui"
    source_dir_mode="host-dist"
    printf '%s\n' "Host dist/control-ui matches the current git checkout; using it as the upstream Control UI source"
  else
    source_dir_mode="image-sourced"
    if gateway_image_matches_current_checkout_for_direct_deploy "$image_ref"; then
      if [[ -f "$ROOT_DIR/dist/control-ui/index.html" ]]; then
        printf '%s\n' "Host dist/control-ui exists but is not stamped for the current git checkout; reusing the current gateway image because only zero-intrusive files changed since it was built"
      else
        printf '%s\n' "Host dist/control-ui is missing; reusing the current gateway image because only zero-intrusive files changed since it was built"
      fi
    else
      if should_skip_gateway_image_build && ! gateway_image_exists_locally "$image_ref"; then
        fail "OPENCLAW_SKIP_GATEWAY_IMAGE_BUILD=1 was set, but $image_ref is not available locally."
      fi
      if [[ -f "$ROOT_DIR/dist/control-ui/index.html" ]]; then
        printf '%s\n' "Host dist/control-ui exists but is not stamped for the current git checkout; rebuilding gateway image and extracting /app/dist/control-ui instead"
      else
        printf '%s\n' "Host dist/control-ui is missing or not trusted for the current git checkout; rebuilding gateway image and extracting /app/dist/control-ui instead"
      fi
      ensure_gateway_service_image_current
      gateway_image_ready="1"
    fi
    source_dir="$(resolve_source_dir image-only)"
  fi

  run_custom_control_ui_builder "$source_dir"
  if [[ "$gateway_image_ready" != "1" ]]; then
    if gateway_image_matches_current_checkout_for_direct_deploy "$image_ref"; then
      printf '%s\n' "Skipped docker compose build for openclaw-gateway because the current image already covers this checkout"
    else
      if should_skip_gateway_image_build && ! gateway_image_exists_locally "$image_ref"; then
        fail "OPENCLAW_SKIP_GATEWAY_IMAGE_BUILD=1 was set, but $image_ref is not available locally."
      fi
      ensure_gateway_service_image_current
    fi
  fi
  prepare_tenant_platform_runtime_node_modules "$image_ref"
  prepare_tenant_platform_runtime_python_packages "$image_ref"
  collect_extra_mounts
  write_override "${COLLECTED_EXTRA_MOUNTS[@]}"
  sync_workspace_overlays
  sync_managed_tenant_member_bootstrap_hook
  sync_portable_baseline_config
  sync_tenant_member_bootstrap_hook_config
  sync_gateway_control_ui_root
  sync_control_ui_allowed_origins
  sync_control_ui_host_header_origin_fallback_disabled
  sync_control_ui_device_auth_bypass
  if run_targeted_compose_up; then
    compose_up_applied="1"
  else
    compose_up_applied="0"
  fi

  printf '%s\n' "Custom Control UI root written to: $OUTPUT_DIR"
  printf '%s\n' "Wrote $OVERRIDE_PATH"
  if [[ "${#COLLECTED_EXTRA_MOUNTS[@]}" -gt 0 ]]; then
    printf '%s\n' "Included ${#COLLECTED_EXTRA_MOUNTS[@]} extra bind mount(s) from OPENCLAW_EXTRA_MOUNTS."
  fi
  if [[ "$compose_up_applied" == "1" ]]; then
    printf '%s\n' "Applied the zero-intrusive docker compose deployment for the related services."
  else
    printf '%s\n' 'Skipped docker compose up; run `docker compose up -d --force-recreate openclaw-gateway openclaw-tenant-platform openclaw-gateway-proxy` when you want to apply the deployment.'
  fi
}

main "$@"
