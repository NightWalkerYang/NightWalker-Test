#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TOOL_DIR="$ROOT_DIR/tools/openclaw-control-ui-echarts"
OUTPUT_DIR="$TOOL_DIR/generated/control-ui"
CONTROL_UI_RUNTIME_SCRIPT="$TOOL_DIR/openclaw-echarts-renderer.js"
CONTROL_UI_RUNTIME_MODULE_DIR="$TOOL_DIR/runtime"
OFFLINE_BUNDLED_USERSCRIPT="$ROOT_DIR/tools/openclaw-echarts-userscript/openclaw-echarts-renderer.user.js"
OVERRIDE_PATH="$ROOT_DIR/docker-compose.override.yml"
ENV_FILE="$ROOT_DIR/.env"

GENERATED_MARKER="# Generated by tools/openclaw-control-ui-echarts setup tool"
LEGACY_GENERATED_MARKER="# Generated by tools/openclaw-control-ui-echarts/setup-direct-docker-compose-up.mjs"

tmp_dir="$(mktemp -d)"
container_id=""

cleanup() {
  if [[ -n "$container_id" ]]; then
    docker rm -f "$container_id" >/dev/null 2>&1 || true
  fi
  rm -rf "$tmp_dir"
}
trap cleanup EXIT

COLLECTED_EXTRA_MOUNTS=()

fail() {
  printf '%s\n' "ERROR: $*" >&2
  exit 1
}

require_file() {
  local file_path="$1"
  local label="$2"
  [[ -f "$file_path" ]] || fail "$label not found at $file_path"
}

require_dir() {
  local dir_path="$1"
  local label="$2"
  [[ -d "$dir_path" ]] || fail "$label not found at $dir_path"
}

trim_whitespace() {
  local value="$1"
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  printf '%s\n' "$value"
}

read_dotenv_value() {
  local key="$1"
  [[ -f "$ENV_FILE" ]] || return 0

  awk -F= -v key="$key" '
    index($0, key "=") == 1 {
      sub(/^[^=]*=/, "")
      sub(/\r$/, "")
      print
      exit
    }
  ' "$ENV_FILE"
}

validate_extra_mount_spec() {
  local mount="$1"

  [[ "$mount" == *$'\n'* || "$mount" == *$'\r'* || "$mount" == *$'\t'* ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS entries cannot contain control characters."

  [[ "$mount" =~ [[:space:]] ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS entries must not contain spaces."

  [[ "$mount" == *:* ]] || fail "Invalid OPENCLAW_EXTRA_MOUNTS entry: $mount"
}

collect_extra_mounts() {
  local raw_mounts="${OPENCLAW_EXTRA_MOUNTS:-}"
  local mount=""

  COLLECTED_EXTRA_MOUNTS=()

  if [[ -z "$raw_mounts" ]]; then
    raw_mounts="$(read_dotenv_value OPENCLAW_EXTRA_MOUNTS || true)"
  fi

  raw_mounts="$(trim_whitespace "$raw_mounts")"
  [[ -n "$raw_mounts" ]] || return 0

  [[ "$raw_mounts" == *$'\n'* || "$raw_mounts" == *$'\r'* || "$raw_mounts" == *$'\t'* ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS cannot contain control characters."

  IFS=',' read -r -a mounts <<<"$raw_mounts"
  for mount in "${mounts[@]}"; do
    mount="$(trim_whitespace "$mount")"
    [[ -n "$mount" ]] || continue
    validate_extra_mount_spec "$mount"
    COLLECTED_EXTRA_MOUNTS+=("$mount")
  done
}

resolve_python() {
  if command -v python3 >/dev/null 2>&1; then
    printf '%s\n' "python3"
    return 0
  fi

  if command -v python >/dev/null 2>&1; then
    printf '%s\n' "python"
    return 0
  fi

  fail "python3 or python is required to extract the bundled vendor libraries."
}

resolve_gateway_image_ref() {
  if [[ -n "${OPENCLAW_IMAGE:-}" ]]; then
    printf '%s\n' "$OPENCLAW_IMAGE"
    return 0
  fi

  local compose_image=""
  compose_image="$(
    docker compose config 2>/dev/null | awk '
      $1 == "openclaw-gateway:" {
        in_service = 1
        next
      }
      in_service && /^[^[:space:]]/ {
        in_service = 0
      }
      in_service && $1 == "image:" {
        print $2
        exit
      }
    '
  )"

  if [[ -n "$compose_image" ]]; then
    printf '%s\n' "$compose_image"
    return 0
  fi

  printf '%s\n' "openclaw:local"
}

ensure_gateway_image_available() {
  local image_ref="$1"

  if docker image inspect "$image_ref" >/dev/null 2>&1; then
    return 0
  fi

  if [[ "$image_ref" == "openclaw:local" ]]; then
    printf '%s\n' "No local $image_ref image found; building it from Dockerfile..." >&2
    docker build -t "$image_ref" -f Dockerfile .
  else
    printf '%s\n' "Image $image_ref is not available locally; pulling it now..." >&2
    docker pull "$image_ref"
  fi

  docker image inspect "$image_ref" >/dev/null 2>&1 || fail "Could not resolve a local openclaw-gateway image."
}

write_override() {
  if [[ -f "$OVERRIDE_PATH" ]]; then
    if ! grep -Fq "$GENERATED_MARKER" "$OVERRIDE_PATH" && \
      ! grep -Fq "$LEGACY_GENERATED_MARKER" "$OVERRIDE_PATH"; then
      fail "Refusing to overwrite existing docker-compose.override.yml at $OVERRIDE_PATH because it was not generated by this tool."
    fi
  fi

  cat >"$OVERRIDE_PATH" <<EOF
$GENERATED_MARKER
services:
  openclaw-gateway:
    volumes:
      - ./tools/openclaw-control-ui-echarts/generated/control-ui:/app/dist/control-ui:ro
      - \${OPENCLAW_WORKSPACE_DIR}:/app/dist/control-ui/workspace-downloads:ro
      - ./docs/reference/templates:/app/docs/reference/templates:ro
EOF

  local mount=""
  for mount in "$@"; do
    printf '      - %s\n' "$mount" >>"$OVERRIDE_PATH"
  done

  if [[ "$#" -gt 0 ]]; then
    cat >>"$OVERRIDE_PATH" <<'EOF'
  openclaw-cli:
    volumes:
EOF

    for mount in "$@"; do
      printf '      - %s\n' "$mount" >>"$OVERRIDE_PATH"
    done
  fi
}

inject_runtime_script() {
  local index_path="$1"
  local temp_index="$index_path.tmp"

  grep -Fq 'openclaw-echarts-renderer.js' "$index_path" && return 0

  awk '
    $0 == "  </body>" {
      print "    <script type=\"module\" src=\"./assets/openclaw-echarts-renderer.js\"></script>"
    }
    { print }
  ' "$index_path" >"$temp_index"

  mv "$temp_index" "$index_path"
  grep -Fq 'openclaw-echarts-renderer.js' "$index_path" || fail "Failed to inject the ECharts runtime into $index_path"
}

extract_offline_vendors() {
  local bundle_path="$1"
  local vendor_dir="$2"
  local python_bin

  python_bin="$(resolve_python)"
  mkdir -p "$vendor_dir"

  "$python_bin" - "$bundle_path" "$vendor_dir" <<'PY'
import json
import pathlib
import re
import sys

bundle_path = pathlib.Path(sys.argv[1])
vendor_dir = pathlib.Path(sys.argv[2])
bundle_source = bundle_path.read_text(encoding="utf-8")
match = re.search(
    r'const EMBEDDED_LIBRARY_SOURCES = \{\s*echarts:\s*("(?:\\.|[^"\\])*")\s*,\s*json5:\s*("(?:\\.|[^"\\])*")\s*,\s*\};',
    bundle_source,
    re.S,
)
if not match:
    raise SystemExit(
        f"ERROR: Could not extract embedded vendor sources from {bundle_path}"
    )

(vendor_dir / "echarts.min.js").write_text(json.loads(match.group(1)), encoding="utf-8")
(vendor_dir / "json5.min.js").write_text(json.loads(match.group(2)), encoding="utf-8")
PY

  [[ -f "$vendor_dir/echarts.min.js" ]] || fail "Failed to write $vendor_dir/echarts.min.js"
  [[ -f "$vendor_dir/json5.min.js" ]] || fail "Failed to write $vendor_dir/json5.min.js"
}

resolve_source_dir() {
  if [[ -f "$ROOT_DIR/dist/control-ui/index.html" ]]; then
    printf '%s\n' "$ROOT_DIR/dist/control-ui"
    return 0
  fi

  command -v docker >/dev/null 2>&1 || fail "docker is required when dist/control-ui is not present on the host."

  printf '%s\n' "Host dist/control-ui is missing; extracting it from the Docker image..." >&2

  local image_ref
  image_ref="$(resolve_gateway_image_ref)"
  ensure_gateway_image_available "$image_ref"

  local extracted_dir="$tmp_dir/source-control-ui"
  mkdir -p "$extracted_dir"

  container_id="$(docker create "$image_ref")"
  docker cp "$container_id:/app/dist/control-ui/." "$extracted_dir"
  docker rm -f "$container_id" >/dev/null 2>&1 || true
  container_id=""

  [[ -f "$extracted_dir/index.html" ]] || fail "The Docker image does not contain /app/dist/control-ui/index.html"
  printf '%s\n' "$extracted_dir"
}

main() {
  require_file "$CONTROL_UI_RUNTIME_SCRIPT" "Control UI ECharts runtime"
  require_dir "$CONTROL_UI_RUNTIME_MODULE_DIR" "Control UI ECharts runtime modules"
  require_file "$OFFLINE_BUNDLED_USERSCRIPT" "Offline bundled ECharts userscript"

  local source_dir
  source_dir="$(resolve_source_dir)"

  rm -rf "$OUTPUT_DIR"
  mkdir -p "$OUTPUT_DIR/assets/vendor"
  cp -R "$source_dir"/. "$OUTPUT_DIR"/
  mkdir -p "$OUTPUT_DIR/workspace-downloads"

  cp "$CONTROL_UI_RUNTIME_SCRIPT" "$OUTPUT_DIR/assets/openclaw-echarts-renderer.js"
  cp -R "$CONTROL_UI_RUNTIME_MODULE_DIR" "$OUTPUT_DIR/assets/runtime"
  extract_offline_vendors "$OFFLINE_BUNDLED_USERSCRIPT" "$OUTPUT_DIR/assets/vendor"

  [[ -f "$OUTPUT_DIR/index.html" ]] || fail "Generated Control UI root is missing index.html"
  inject_runtime_script "$OUTPUT_DIR/index.html"
  collect_extra_mounts
  write_override "${COLLECTED_EXTRA_MOUNTS[@]}"

  printf '%s\n' "Custom Control UI root written to: $OUTPUT_DIR"
  printf '%s\n' "Wrote $OVERRIDE_PATH"
  if [[ "${#COLLECTED_EXTRA_MOUNTS[@]}" -gt 0 ]]; then
    printf '%s\n' "Included ${#COLLECTED_EXTRA_MOUNTS[@]} extra bind mount(s) from OPENCLAW_EXTRA_MOUNTS."
  fi
  printf '%s\n' 'You can now run `docker compose up -d` from the repo root and the custom Control UI will be mounted automatically.'
}

main "$@"
