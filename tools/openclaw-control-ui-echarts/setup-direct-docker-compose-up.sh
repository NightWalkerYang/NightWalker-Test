inject_auto_gateway_token_bootstrap() {
  local index_path="$1"
  local token="$2"
  local python_bin

  token="$(trim_whitespace "$token")"
  [[ -n "$token" ]] || return 0

  python_bin="$(resolve_python)"

  "$python_bin" - "$index_path" "$token" <<'PY'
import json
import pathlib
import sys

index_path = pathlib.Path(sys.argv[1])
token = (sys.argv[2] or "").strip()
if not token:
    raise SystemExit(0)

html = index_path.read_text(encoding="utf-8")
if "data-openclaw-auto-token-bootstrap" in html:
    raise SystemExit(0)

token_literal = (
    json.dumps(token)
    .replace("<", "\\u003c")
    .replace(">", "\\u003e")
    .replace("&", "\\u0026")
    .replace("\u2028", "\\u2028")
    .replace("\u2029", "\\u2029")
)
script = f"""    <script data-openclaw-auto-token-bootstrap>
      ((rawToken) => {{
        const CONTROL_UI_TAB_PATHS = new Set([
          "/agents",
          "/overview",
          "/channels",
          "/instances",
          "/sessions",
          "/usage",
          "/cron",
          "/skills",
          "/nodes",
          "/chat",
          "/config",
          "/communications",
          "/appearance",
          "/automation",
          "/infrastructure",
          "/ai-agents",
          "/debug",
          "/logs",
        ]);
        const normalizeBasePath = (basePath) => {{
          if (!basePath) return "";
          let base = String(basePath).trim();
          if (!base) return "";
          if (!base.startsWith("/")) base = `/${{base}}`;
          if (base === "/") return "";
          if (base.endsWith("/")) base = base.slice(0, -1);
          return base;
        }};
        const normalizePath = (value) => {{
          if (!value) return "/";
          let normalized = String(value).trim();
          if (!normalized.startsWith("/")) normalized = `/${{normalized}}`;
          if (normalized.length > 1 && normalized.endsWith("/")) {{
            normalized = normalized.slice(0, -1);
          }}
          return normalized;
        }};
        const inferBasePathFromPathname = (pathname) => {{
          let normalized = normalizePath(pathname);
          if (normalized.endsWith("/index.html")) {{
            normalized = normalizePath(normalized.slice(0, -"/index.html".length));
          }}
          if (normalized === "/") return "";
          const segments = normalized.split("/").filter(Boolean);
          if (segments.length === 0) return "";
          for (let index = 0; index < segments.length; index += 1) {{
            const candidate = `/${{segments.slice(index).join("/")}}`.toLowerCase();
            if (CONTROL_UI_TAB_PATHS.has(candidate)) {{
              const prefix = segments.slice(0, index);
              return prefix.length > 0 ? `/${{prefix.join("/")}}` : "";
            }}
          }}
          return `/${{segments.join("/")}}`;
        }};
        const normalizeGatewayTokenScope = (gatewayUrl) => {{
          const trimmed = String(gatewayUrl || "").trim();
          if (!trimmed) return "default";
          try {{
            const base =
              typeof location !== "undefined"
                ? `${{location.protocol}}//${{location.host}}${{location.pathname || "/"}}`
                : undefined;
            const parsed = base ? new URL(trimmed, base) : new URL(trimmed);
            const pathname =
              parsed.pathname === "/"
                ? ""
                : parsed.pathname.replace(/\\/+$/, "") || parsed.pathname;
            return `${{parsed.protocol}}//${{parsed.host}}${{pathname}}`;
          }} catch {{
            return trimmed;
          }}
        }};
        const token = String(rawToken ?? "").trim();
        if (!token || typeof window === "undefined" || typeof location === "undefined") {{
          return;
        }}
        try {{
          const storage = window.sessionStorage;
          if (!storage) return;
          const configured =
            typeof window.__OPENCLAW_CONTROL_UI_BASE_PATH__ === "string" &&
            window.__OPENCLAW_CONTROL_UI_BASE_PATH__.trim();
          const basePath = configured
            ? normalizeBasePath(window.__OPENCLAW_CONTROL_UI_BASE_PATH__)
            : inferBasePathFromPathname(location.pathname);
          const proto = location.protocol === "https:" ? "wss" : "ws";
          const gatewayUrl = `${{proto}}://${{location.host}}${{basePath}}`;
          const scope = normalizeGatewayTokenScope(gatewayUrl);
          storage.setItem(`openclaw.control.token.v1:${{scope}}`, token);
          window.__OPENCLAW_CONTROL_UI_AUTO_TOKEN__ = true;
        }} catch {{
          // best-effort only
        }}
      }})({token_literal});
    </script>
"""

if "</head>" not in html:
    raise SystemExit(f"index.html is missing </head>: {index_path}")

html = html.replace("  </head>", f"{script}\n  </head>", 1)
index_path.write_text(html, encoding="utf-8")
PY
}

extract_offline_vendors() {
  local bundle_path="$1"
  local vendor_dir="$2"
  local python_bin

  python_bin="$(resolve_python)"
  mkdir -p "$vendor_dir"

  "$python_bin" - "$bundle_path" "$vendor_dir" <<'PY'
import json
import pathlib
import re
import sys

bundle_path = pathlib.Path(sys.argv[1])
vendor_dir = pathlib.Path(sys.argv[2])
bundle_source = bundle_path.read_text(encoding="utf-8")
match = re.search(
    r'const EMBEDDED_LIBRARY_SOURCES = \{\s*echarts:\s*("(?:\\.|[^"\\])*")\s*,\s*json5:\s*("(?:\\.|[^"\\])*")\s*,\s*\};',
    bundle_source,
    re.S,
)
if not match:
    raise SystemExit(
        f"ERROR: Could not extract embedded vendor sources from {bundle_path}"
    )

(vendor_dir / "echarts.min.js").write_text(json.loads(match.group(1)), encoding="utf-8")
(vendor_dir / "json5.min.js").write_text(json.loads(match.group(2)), encoding="utf-8")
PY

  [[ -f "$vendor_dir/echarts.min.js" ]] || fail "Failed to write $vendor_dir/echarts.min.js"
  [[ -f "$vendor_dir/json5.min.js" ]] || fail "Failed to write $vendor_dir/json5.min.js"
}

resolve_source_dir() {
  if [[ -f "$ROOT_DIR/dist/control-ui/index.html" ]]; then
    printf '%s\n' "$ROOT_DIR/dist/control-ui"
    return 0
  fi

  command -v docker >/dev/null 2>&1 || fail "docker is required when dist/control-ui is not present on the host."

  printf '%s\n' "Host dist/control-ui is missing; extracting it from the Docker image..." >&2

  local image_ref
  image_ref="$(resolve_gateway_image_ref)"
  ensure_gateway_image_available "$image_ref"

  local extracted_dir="$tmp_dir/source-control-ui"
  mkdir -p "$extracted_dir"

  container_id="$(docker create "$image_ref")"
  docker cp "$container_id:/app/dist/control-ui/." "$extracted_dir"
  docker rm -f "$container_id" >/dev/null 2>&1 || true
  container_id=""

  [[ -f "$extracted_dir/index.html" ]] || fail "The Docker image does not contain /app/dist/control-ui/index.html"
  printf '%s\n' "$extracted_dir"
}

main() {
  require_file "$CONTROL_UI_RUNTIME_SCRIPT" "Control UI ECharts runtime"
  require_dir "$CONTROL_UI_RUNTIME_MODULE_DIR" "Control UI ECharts runtime modules"
  require_dir "$CONTROL_UI_STATIC_DIR" "Control UI static overlay assets"
  require_file "$OFFLINE_BUNDLED_USERSCRIPT" "Offline bundled ECharts userscript"

  local source_dir
  source_dir="$(resolve_source_dir)"

  rm -rf "$OUTPUT_DIR"
  mkdir -p "$OUTPUT_DIR/assets/vendor"
  cp -R "$source_dir"/. "$OUTPUT_DIR"/
  cp -R "$CONTROL_UI_STATIC_DIR"/. "$OUTPUT_DIR"/
  mkdir -p "$OUTPUT_DIR/workspace-downloads"

  cp "$CONTROL_UI_RUNTIME_SCRIPT" "$OUTPUT_DIR/assets/openclaw-echarts-renderer.js"
  cp -R "$CONTROL_UI_RUNTIME_MODULE_DIR" "$OUTPUT_DIR/assets/runtime"
  extract_offline_vendors "$OFFLINE_BUNDLED_USERSCRIPT" "$OUTPUT_DIR/assets/vendor"

  [[ -f "$OUTPUT_DIR/index.html" ]] || fail "Generated Control UI root is missing index.html"
  local auto_gateway_token
  auto_gateway_token="$(resolve_auto_gateway_token)"
  inject_lufeng_public_bootstrap "$OUTPUT_DIR/index.html" "$auto_gateway_token"
  inject_auto_gateway_token_bootstrap "$OUTPUT_DIR/index.html" "$auto_gateway_token"
  inject_runtime_script "$OUTPUT_DIR/index.html"
  replace_brand_favicons "$OUTPUT_DIR/index.html"
  collect_extra_mounts
  write_override "${COLLECTED_EXTRA_MOUNTS[@]}"

  printf '%s\n' "Custom Control UI root written to: $OUTPUT_DIR"
  printf '%s\n' "Wrote $OVERRIDE_PATH"
  if [[ "${#COLLECTED_EXTRA_MOUNTS[@]}" -gt 0 ]]; then
    printf '%s\n' "Included ${#COLLECTED_EXTRA_MOUNTS[@]} extra bind mount(s) from OPENCLAW_EXTRA_MOUNTS."
  fi
  printf '%s\n' 'You can now run `docker compose up -d` from the repo root and the custom Control UI will be mounted automatically.'
}

main "$@"
