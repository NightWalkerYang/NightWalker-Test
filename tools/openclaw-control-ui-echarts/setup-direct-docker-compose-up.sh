#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TOOL_DIR="$ROOT_DIR/tools/openclaw-control-ui-echarts"
OUTPUT_DIR="$TOOL_DIR/generated/control-ui"
CONTROL_UI_RUNTIME_SCRIPT="$TOOL_DIR/openclaw-echarts-renderer.js"
CONTROL_UI_RUNTIME_MODULE_DIR="$TOOL_DIR/runtime"
CONTROL_UI_STATIC_DIR="$TOOL_DIR/static"
OFFLINE_BUNDLED_USERSCRIPT="$ROOT_DIR/tools/openclaw-echarts-userscript/openclaw-echarts-renderer.user.js"
OVERRIDE_PATH="$ROOT_DIR/docker-compose.override.yml"
ENV_FILE="$ROOT_DIR/.env"

GENERATED_MARKER="# Generated by tools/openclaw-control-ui-echarts setup tool"
LEGACY_GENERATED_MARKER="# Generated by tools/openclaw-control-ui-echarts/setup-direct-docker-compose-up.mjs"

tmp_dir="$(mktemp -d)"
container_id=""

cleanup() {
  if [[ -n "$container_id" ]]; then
    docker rm -f "$container_id" >/dev/null 2>&1 || true
  fi
  rm -rf "$tmp_dir"
}
trap cleanup EXIT

COLLECTED_EXTRA_MOUNTS=()

fail() {
  printf '%s\n' "ERROR: $*" >&2
  exit 1
}

require_file() {
  local file_path="$1"
  local label="$2"
  [[ -f "$file_path" ]] || fail "$label not found at $file_path"
}

require_dir() {
  local dir_path="$1"
  local label="$2"
  [[ -d "$dir_path" ]] || fail "$label not found at $dir_path"
}

trim_whitespace() {
  local value="$1"
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  printf '%s\n' "$value"
}

read_dotenv_value() {
  local key="$1"
  [[ -f "$ENV_FILE" ]] || return 0

  awk -F= -v key="$key" '
    index($0, key "=") == 1 {
      sub(/^[^=]*=/, "")
      sub(/\r$/, "")
      print
      exit
    }
  ' "$ENV_FILE"
}

resolve_auto_gateway_token() {
  local token="${OPENCLAW_GATEWAY_TOKEN:-}"
  if [[ -z "$token" ]]; then
    token="$(read_dotenv_value OPENCLAW_GATEWAY_TOKEN || true)"
  fi
  trim_whitespace "$token"
}

inject_lufeng_public_bootstrap() {
  local index_path="$1"
  local token="$2"
  local python_bin

  python_bin="$(resolve_python)"

  "$python_bin" - "$index_path" "$token" <<'PY'
import json
import pathlib
import sys

index_path = pathlib.Path(sys.argv[1])
token = (sys.argv[2] or "").strip()

html = index_path.read_text(encoding="utf-8")
if "data-openclaw-lufeng-bootstrap" in html:
    raise SystemExit(0)

agent_id = "subotech-finance"
session_key = f"agent:{agent_id}:main"
route = "/lufeng"
route_chat = "/lufeng/chat"

token_literal = (
    json.dumps(token)
    .replace("<", "\\u003c")
    .replace(">", "\\u003e")
    .replace("&", "\\u0026")
    .replace("\u2028", "\\u2028")
    .replace("\u2029", "\\u2029")
)

script = f"""    <script data-openclaw-lufeng-bootstrap>
      ((rawToken) => {{
        const ROUTE = {json.dumps(route)};
        const CHAT_ROUTE = {json.dumps(route_chat)};
        const SESSION_KEY = {json.dumps(session_key)};
        const normalizePath = (value) => {{
          const raw = String(value ?? "").trim() || "/";
          const prefixed = raw.startsWith("/") ? raw : `/${{raw}}`;
          if (prefixed.length > 1 && prefixed.endsWith("/")) {{
            return prefixed.slice(0, -1);
          }}
          return prefixed;
        }};
        const isLufengPath = (pathname) => {{
          const normalized = normalizePath(pathname);
          return normalized === ROUTE || normalized === CHAT_ROUTE;
        }};
        if (
          typeof window === "undefined" ||
          typeof document === "undefined" ||
          typeof location === "undefined" ||
          !isLufengPath(location.pathname)
        ) {{
          return;
        }}
        const normalizeGatewayScope = (gatewayUrl) => {{
          const trimmed = String(gatewayUrl ?? "").trim();
          if (!trimmed) {{
            return "default";
          }}
          try {{
            const parsed = new URL(
              trimmed,
              `${{window.location.protocol}}//${{window.location.host}}/`,
            );
            const pathname =
              parsed.pathname === "/"
                ? ""
                : parsed.pathname.replace(/\\/+$/, "") || parsed.pathname;
            return `${{parsed.protocol}}//${{parsed.host}}${{pathname}}`;
          }} catch {{
            return trimmed;
          }}
        }};
        const buildSettingsStorageKey = (gatewayUrl) =>
          `openclaw.control.settings.v1:${{normalizeGatewayScope(gatewayUrl)}}`;
        const buildTokenStorageKey = (gatewayUrl) =>
          `openclaw.control.token.v1:${{normalizeGatewayScope(gatewayUrl)}}`;
        const normalizeLufengRouteUrl = (urlLike, baseHref = window.location.href) => {{
          const url = new URL(urlLike, baseHref);
          if (!isLufengPath(url.pathname)) {{
            return url;
          }}
          const normalized = normalizePath(url.pathname);
          if (normalized === CHAT_ROUTE) {{
            url.pathname = ROUTE;
          }}
          if (normalizePath(url.pathname) === ROUTE) {{
            url.searchParams.delete("session");
          }}
          return url;
        }};

        const gatewayOrigin = `${{location.protocol === "https:" ? "wss:" : "ws:"}}//${{location.host}}`;
        const lufengScopeUrl = `${{gatewayOrigin}}${{ROUTE}}`;
        const rootGatewayScope = normalizeGatewayScope(gatewayOrigin);

        window.__OPENCLAW_CONTROL_UI_BASE_PATH__ = ROUTE;
        window.__OPENCLAW_LUFENG_MODE__ = true;
        document.documentElement.setAttribute("data-oc-lufeng-route", "true");

        try {{
          const storage = window.localStorage;
          if (storage) {{
            const key = buildSettingsStorageKey(lufengScopeUrl);
            const existingRaw = storage.getItem(key);
            const existing =
              existingRaw && existingRaw.trim()
                ? JSON.parse(existingRaw)
                : {{}};
            const next = {{
              ...existing,
              gatewayUrl: gatewayOrigin,
              sessionKey: SESSION_KEY,
              lastActiveSessionKey: SESSION_KEY,
              sessionsByGateway: {{
                ...(existing.sessionsByGateway && typeof existing.sessionsByGateway === "object"
                  ? existing.sessionsByGateway
                  : {{}}),
                [rootGatewayScope]: {{
                  sessionKey: SESSION_KEY,
                  lastActiveSessionKey: SESSION_KEY,
                }},
              }},
            }};
            storage.setItem(key, JSON.stringify(next));
          }}
        }} catch {{
          // best-effort only
        }}

        try {{
          const normalizedToken = String(rawToken ?? "").trim();
          if (normalizedToken && window.sessionStorage) {{
            window.sessionStorage.setItem(
              buildTokenStorageKey(gatewayOrigin),
              normalizedToken,
            );
          }}
        }} catch {{
          // best-effort only
        }}

        if (!window.__OPENCLAW_LUFENG_HISTORY_PATCHED__) {{
          const originalReplaceState = window.history.replaceState.bind(window.history);
          const originalPushState = window.history.pushState.bind(window.history);
          const wrap =
            (original) =>
            (state, unused, url) => {{
              if (url == null) {{
                return original(state, unused, url);
              }}
              const normalized = normalizeLufengRouteUrl(url, window.location.href);
              return original(state, unused, normalized.toString());
            }};
          window.history.replaceState = wrap(originalReplaceState);
          window.history.pushState = wrap(originalPushState);
          window.__OPENCLAW_LUFENG_HISTORY_PATCHED__ = true;
        }}

        const normalizedCurrent = normalizeLufengRouteUrl(window.location.href, window.location.href);
        if (
          normalizedCurrent.pathname !== window.location.pathname ||
          normalizedCurrent.search !== window.location.search
        ) {{
          window.history.replaceState({{}}, "", normalizedCurrent.toString());
        }}
      }})({token_literal});
    </script>
"""

if "</head>" not in html:
    raise SystemExit(f"index.html is missing </head>: {index_path}")

html = html.replace("  </head>", f"{script}\n  </head>", 1)
index_path.write_text(html, encoding="utf-8")
PY
}

validate_extra_mount_spec() {
  local mount="$1"

  [[ "$mount" == *$'\n'* || "$mount" == *$'\r'* || "$mount" == *$'\t'* ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS entries cannot contain control characters."

  [[ "$mount" =~ [[:space:]] ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS entries must not contain spaces."

  [[ "$mount" == *:* ]] || fail "Invalid OPENCLAW_EXTRA_MOUNTS entry: $mount"
}

collect_extra_mounts() {
  local raw_mounts="${OPENCLAW_EXTRA_MOUNTS:-}"
  local mount=""

  COLLECTED_EXTRA_MOUNTS=()

  if [[ -z "$raw_mounts" ]]; then
    raw_mounts="$(read_dotenv_value OPENCLAW_EXTRA_MOUNTS || true)"
  fi

  raw_mounts="$(trim_whitespace "$raw_mounts")"
  [[ -n "$raw_mounts" ]] || return 0

  [[ "$raw_mounts" == *$'\n'* || "$raw_mounts" == *$'\r'* || "$raw_mounts" == *$'\t'* ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS cannot contain control characters."

  IFS=',' read -r -a mounts <<<"$raw_mounts"
  for mount in "${mounts[@]}"; do
    mount="$(trim_whitespace "$mount")"
    [[ -n "$mount" ]] || continue
    validate_extra_mount_spec "$mount"
    COLLECTED_EXTRA_MOUNTS+=("$mount")
  done
}

resolve_python() {
  if command -v python3 >/dev/null 2>&1; then
    printf '%s\n' "python3"
    return 0
  fi

  if command -v python >/dev/null 2>&1; then
    printf '%s\n' "python"
    return 0
  fi

  fail "python3 or python is required to extract the bundled vendor libraries."
}

resolve_gateway_image_ref() {
  if [[ -n "${OPENCLAW_IMAGE:-}" ]]; then
    printf '%s\n' "$OPENCLAW_IMAGE"
    return 0
  fi

  local compose_image=""
  compose_image="$(
    docker compose config 2>/dev/null | awk '
      $1 == "openclaw-gateway:" {
        in_service = 1
        next
      }
      in_service && /^[^[:space:]]/ {
        in_service = 0
      }
      in_service && $1 == "image:" {
        print $2
        exit
      }
    '
  )"

  if [[ -n "$compose_image" ]]; then
    printf '%s\n' "$compose_image"
    return 0
  fi

  printf '%s\n' "openclaw:local"
}

ensure_gateway_image_available() {
  local image_ref="$1"

  if docker image inspect "$image_ref" >/dev/null 2>&1; then
    return 0
  fi

  if [[ "$image_ref" == "openclaw:local" ]]; then
    printf '%s\n' "No local $image_ref image found; building it from Dockerfile..." >&2
    docker build -t "$image_ref" -f Dockerfile .
  else
    printf '%s\n' "Image $image_ref is not available locally; pulling it now..." >&2
    docker pull "$image_ref"
  fi

  docker image inspect "$image_ref" >/dev/null 2>&1 || fail "Could not resolve a local openclaw-gateway image."
}

write_override() {
  if [[ -f "$OVERRIDE_PATH" ]]; then
    if ! grep -Fq "$GENERATED_MARKER" "$OVERRIDE_PATH" && \
      ! grep -Fq "$LEGACY_GENERATED_MARKER" "$OVERRIDE_PATH"; then
      fail "Refusing to overwrite existing docker-compose.override.yml at $OVERRIDE_PATH because it was not generated by this tool."
    fi
  fi

  cat >"$OVERRIDE_PATH" <<EOF
$GENERATED_MARKER
services:
  openclaw-gateway:
    volumes:
      - ./tools/openclaw-control-ui-echarts/generated/control-ui:/app/dist/control-ui:ro
      - \${OPENCLAW_WORKSPACE_DIR}:/app/dist/control-ui/workspace-downloads:ro
      - ./docs/reference/templates:/app/docs/reference/templates:ro
EOF

  local mount=""
  for mount in "$@"; do
    printf '      - %s\n' "$mount" >>"$OVERRIDE_PATH"
  done

  cat >>"$OVERRIDE_PATH" <<'EOF'
  openclaw-tenant-platform:
    image: ${OPENCLAW_IMAGE:-openclaw:local}
    environment:
      HOME: /home/node
      OPENCLAW_CONFIG_DIR: /home/node/.openclaw
