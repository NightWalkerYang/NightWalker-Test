COLLECTED_EXTRA_MOUNTS=()

fail() {
  printf '%s\n' "ERROR: $*" >&2
  exit 1
}

require_file() {
  local file_path="$1"
  local label="$2"
  [[ -f "$file_path" ]] || fail "$label not found at $file_path"
}

require_dir() {
  local dir_path="$1"
  local label="$2"
  [[ -d "$dir_path" ]] || fail "$label not found at $dir_path"
}

reset_output_dir_preserve_mount() {
  local dir_path="$1"
  mkdir -p "$dir_path"
  find "$dir_path" -mindepth 1 -maxdepth 1 -exec rm -rf -- {} +
}

trim_whitespace() {
  local value="$1"
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  printf '%s\n' "$value"
}

is_truthy_env_value() {
  local value
  value="$(trim_whitespace "${1:-}")"
  value="${value,,}"
  [[ "$value" == "1" || "$value" == "true" || "$value" == "yes" || "$value" == "on" ]]
}

read_dotenv_value() {
  local key="$1"
  [[ -f "$ENV_FILE" ]] || return 0

  awk -F= -v key="$key" '
    index($0, key "=") == 1 {
      sub(/^[^=]*=/, "")
      sub(/\r$/, "")
      print
      exit
    }
  ' "$ENV_FILE"
}

resolve_gateway_port() {
  local port="${OPENCLAW_GATEWAY_PORT:-}"
  if [[ -z "$port" ]]; then
    port="$(read_dotenv_value OPENCLAW_GATEWAY_PORT || true)"
  fi
  port="$(trim_whitespace "$port")"
  if [[ -z "$port" ]]; then
    port="18789"
  fi
  printf '%s\n' "$port"
}

resolve_openclaw_config_dir() {
  local dir="${OPENCLAW_CONFIG_DIR:-}"
  if [[ -z "$dir" ]]; then
    dir="$(read_dotenv_value OPENCLAW_CONFIG_DIR || true)"
  fi
  dir="$(trim_whitespace "$dir")"
  if [[ -z "$dir" ]]; then
    dir="$HOME/.openclaw"
  fi
  printf '%s\n' "$dir"
}

should_skip_compose_up() {
  local value="${OPENCLAW_SKIP_COMPOSE_UP:-}"
  if [[ -z "$value" ]]; then
    value="$(read_dotenv_value OPENCLAW_SKIP_COMPOSE_UP || true)"
  fi
  is_truthy_env_value "$value"
}

merge_control_ui_allowed_origins_json() {
  local port="$1"
  local raw="${2:-}"
  if ! command -v python3 >/dev/null 2>&1; then
    printf '["http://127.0.0.1:%s","http://localhost:%s"]\n' "$port" "$port"
    return 0
  fi

  python3 - "$port" "$raw" <<'PY'
import json
import sys

port = sys.argv[1]
raw = sys.argv[2] if len(sys.argv) > 2 else ""
desired = [
    f"http://127.0.0.1:{port}",
    f"http://localhost:{port}",
]
existing = []
if raw:
    try:
        parsed = json.loads(raw)
        if isinstance(parsed, list):
            existing = parsed
    except json.JSONDecodeError:
        existing = []
merged = []
seen = set()
for origin in existing + desired:
    if not isinstance(origin, str):
        continue
    normalized = origin.strip()
    if not normalized or normalized in seen:
        continue
    merged.append(normalized)
    seen.add(normalized)
print(json.dumps(merged))
PY
}

