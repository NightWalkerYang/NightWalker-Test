}

run_targeted_compose_up() {
  if should_skip_compose_up; then
    printf '%s\n' "Skipped docker compose up because OPENCLAW_SKIP_COMPOSE_UP=1"
    return 1
  fi

  if ! command -v docker >/dev/null 2>&1; then
    fail "docker compose is required to apply the zero-intrusive deployment."
  fi
  if ! (cd "$ROOT_DIR" && docker compose config >/dev/null 2>&1); then
    fail "docker compose is not available in repo root; cannot apply the zero-intrusive deployment."
  fi

  if cd "$ROOT_DIR" && docker compose up -d --force-recreate "${COMPOSE_UP_SERVICES[@]}"; then
    printf '%s\n' "Applied docker compose up --force-recreate for ${COMPOSE_UP_SERVICES[*]}"
    return 0
  fi

  fail "docker compose up failed for ${COMPOSE_UP_SERVICES[*]}"
}

inject_runtime_script() {
