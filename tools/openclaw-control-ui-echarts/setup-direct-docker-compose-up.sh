merge_control_ui_allowed_origins_json() {
  local port="$1"
  local raw="${2:-}"
  if ! command -v python3 >/dev/null 2>&1; then
    printf '["http://127.0.0.1:%s","http://localhost:%s"]\n' "$port" "$port"
    return 0
  fi

  python3 - "$port" "$raw" <<'PY'
import json
import sys

port = sys.argv[1]
raw = sys.argv[2] if len(sys.argv) > 2 else ""
desired = [
    f"http://127.0.0.1:{port}",
    f"http://localhost:{port}",
]
existing = []
if raw:
    try:
        parsed = json.loads(raw)
        if isinstance(parsed, list):
            existing = parsed
    except json.JSONDecodeError:
        existing = []
merged = []
seen = set()
for origin in existing + desired:
    if not isinstance(origin, str):
        continue
    normalized = origin.strip()
    if not normalized or normalized in seen:
        continue
    merged.append(normalized)
    seen.add(normalized)
print(json.dumps(merged))
PY
}

validate_extra_mount_spec() {
  local mount="$1"

  [[ "$mount" == *$'\n'* || "$mount" == *$'\r'* || "$mount" == *$'\t'* ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS entries cannot contain control characters."

  [[ "$mount" =~ [[:space:]] ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS entries must not contain spaces."

  [[ "$mount" == *:* ]] || fail "Invalid OPENCLAW_EXTRA_MOUNTS entry: $mount"
}

collect_extra_mounts() {
  local raw_mounts="${OPENCLAW_EXTRA_MOUNTS:-}"
  local mount=""

  COLLECTED_EXTRA_MOUNTS=()

  if [[ -z "$raw_mounts" ]]; then
    raw_mounts="$(read_dotenv_value OPENCLAW_EXTRA_MOUNTS || true)"
  fi

  raw_mounts="$(trim_whitespace "$raw_mounts")"
  [[ -n "$raw_mounts" ]] || return 0

  [[ "$raw_mounts" == *$'\n'* || "$raw_mounts" == *$'\r'* || "$raw_mounts" == *$'\t'* ]] && \
    fail "OPENCLAW_EXTRA_MOUNTS cannot contain control characters."

  IFS=',' read -r -a mounts <<<"$raw_mounts"
  for mount in "${mounts[@]}"; do
    mount="$(trim_whitespace "$mount")"
    [[ -n "$mount" ]] || continue
    validate_extra_mount_spec "$mount"
    COLLECTED_EXTRA_MOUNTS+=("$mount")
  done
}

run_custom_control_ui_builder() {
  local source_dir="$1"
  local auto_gateway_token="${OPENCLAW_GATEWAY_TOKEN:-}"
  local config_dir=""
  if [[ -z "$auto_gateway_token" ]]; then
    auto_gateway_token="$(read_dotenv_value OPENCLAW_GATEWAY_TOKEN || true)"
  fi
  config_dir="$(resolve_openclaw_config_dir)"

  if command -v node >/dev/null 2>&1; then
    node "$TOOL_DIR/build-custom-control-ui.mjs" --source "$source_dir" --output "$OUTPUT_DIR"
    return 0
  fi

  command -v docker >/dev/null 2>&1 || fail "node or docker is required to build the custom Control UI."

  local image_ref
  local container_output_dir="/workspace/tools/openclaw-control-ui-echarts/generated/control-ui"
  local container_source_dir=""
  image_ref="$(resolve_gateway_image_ref)"
  ensure_gateway_image_available "$image_ref"

  if [[ "$source_dir" == "$ROOT_DIR"* ]]; then
    container_source_dir="/workspace${source_dir#$ROOT_DIR}"
    docker run --rm \
      -v "$ROOT_DIR:/workspace" \
      -v "$config_dir:/tmp/openclaw-config:ro" \
      -w /workspace \
      -e OPENCLAW_CONFIG_DIR=/tmp/openclaw-config \
      -e OPENCLAW_GATEWAY_TOKEN="$auto_gateway_token" \
      "$image_ref" \
      node /workspace/tools/openclaw-control-ui-echarts/build-custom-control-ui.mjs \
        --source "$container_source_dir" \
        --output "$container_output_dir"
    return 0
  fi

  docker run --rm \
    -v "$ROOT_DIR:/workspace" \
    -v "$config_dir:/tmp/openclaw-config:ro" \
    -v "$source_dir:/tmp/openclaw-source-ui:ro" \
    -w /workspace \
    -e OPENCLAW_CONFIG_DIR=/tmp/openclaw-config \
    -e OPENCLAW_GATEWAY_TOKEN="$auto_gateway_token" \
    "$image_ref" \
    node /workspace/tools/openclaw-control-ui-echarts/build-custom-control-ui.mjs \
      --source /tmp/openclaw-source-ui \
      --output "$container_output_dir"
}

docker_compose_available() {
  command -v docker >/dev/null 2>&1 || return 1
  (cd "$ROOT_DIR" && docker compose config >/dev/null 2>&1)
}

resolve_gateway_image_ref() {
  if [[ -n "${OPENCLAW_IMAGE:-}" ]]; then
    printf '%s\n' "$OPENCLAW_IMAGE"
    return 0
  fi

  local compose_image=""
  compose_image="$(
    docker compose config 2>/dev/null | awk '
      $1 == "openclaw-gateway:" {
        in_service = 1
        next
      }
      in_service && /^[^[:space:]]/ {
        in_service = 0
      }
      in_service && $1 == "image:" {
        print $2
        exit
      }
    '
  )"

  if [[ -n "$compose_image" ]]; then
    printf '%s\n' "$compose_image"
    return 0
  fi

  printf '%s\n' "openclaw:local"
}

ensure_gateway_image_available() {
  local image_ref="$1"

  if docker image inspect "$image_ref" >/dev/null 2>&1; then
    return 0
  fi

  if [[ "$image_ref" == "openclaw:local" ]]; then
    printf '%s\n' "No local $image_ref image found; building it from Dockerfile..." >&2
    docker build -t "$image_ref" -f Dockerfile .
  else
    printf '%s\n' "Image $image_ref is not available locally; pulling it now..." >&2
    docker pull "$image_ref"
  fi

  docker image inspect "$image_ref" >/dev/null 2>&1 || fail "Could not resolve a local openclaw-gateway image."
}

ensure_gateway_service_image_current() {
  if should_skip_gateway_image_build; then
    printf '%s\n' "Skipped docker compose build for openclaw-gateway because OPENCLAW_SKIP_GATEWAY_IMAGE_BUILD=1"
    return 0
  fi

  if ! docker_compose_available; then
    return 0
  fi

  if cd "$ROOT_DIR" && OPENCLAW_SKIP_RUNTIME_PRUNE=1 OPENCLAW_DOCKER_APT_PACKAGES="$TENANT_PLATFORM_APT_PACKAGES" docker compose build openclaw-gateway; then
    printf '%s\n' "Rebuilt docker compose image for openclaw-gateway from current repository checkout"
    return 0
  fi

  fail "docker compose build failed for openclaw-gateway"
}

