function writeRootOverride() {
  const extraMounts = getExtraMounts();
  if (fs.existsSync(overridePath)) {
    const existing = fs.readFileSync(overridePath, "utf8");
    if (!LEGACY_GENERATED_MARKERS.some((marker) => existing.includes(marker))) {
      throw new Error(
        `Refusing to overwrite existing docker-compose.override.yml at ${overridePath} because it was not generated by this tool.`,
      );
    }
  }

  fs.writeFileSync(overridePath, buildOverrideContent(extraMounts), "utf8");
  return extraMounts;
}

function ensureGatewayServiceImageCurrent() {
  if (shouldSkipGatewayImageBuild()) {
    process.stdout.write(
      "Skipped docker compose build for openclaw-gateway because OPENCLAW_SKIP_GATEWAY_IMAGE_BUILD=1\n",
    );
    return false;
  }

  if (!dockerComposeAvailable()) {
    return false;
  }

  const result = spawnSync(dockerCommand, ["compose", "build", "openclaw-gateway"], {
    cwd: repoRoot,
    stdio: "inherit",
  });
  if (result.status !== 0) {
    throw new Error(`${dockerCommand} compose build failed for openclaw-gateway.`);
  }

  process.stdout.write(
    "Rebuilt docker compose image for openclaw-gateway from current repository checkout\n",
  );
  return true;
}

function syncGatewayControlUiRoot() {
  if (!dockerComposeAvailable()) {
    process.stderr.write(
      "WARN: docker compose is not available in repo root; skip syncing gateway.controlUi.root.\n",
    );
    return false;
  }

  const result = spawnSync(
    dockerCommand,
    [
      "compose",
      "run",
      "--rm",
      "--no-deps",
      "--entrypoint",
      "node",
      "openclaw-gateway",
      "dist/index.js",
      "config",
      "set",
      "gateway.controlUi.root",
      "/app/dist/control-ui",
    ],
    {
      cwd: repoRoot,
      stdio: "pipe",
      encoding: "utf8",
    },
  );
  if (result.status !== 0) {
    process.stderr.write(
      [
        "WARN: failed to sync gateway.controlUi.root automatically; run this manually:",
        `  ${dockerCommand} compose run --rm --no-deps --entrypoint node openclaw-gateway dist/index.js config set gateway.controlUi.root /app/dist/control-ui`,
      ].join("\n") + "\n",
    );
    return false;
  }
  process.stdout.write("Synced gateway.controlUi.root=/app/dist/control-ui\n");
  return true;
}

function syncControlUiAllowedOrigins() {
  if (!dockerComposeAvailable()) {
    process.stderr.write(
      "WARN: docker compose is not available in repo root; skip syncing gateway.controlUi.allowedOrigins.\n",
    );
    return false;
  }

  let currentAllowedOrigins = "";
  const getResult = spawnSync(
    dockerCommand,
    [
      "compose",
      "run",
      "--rm",
      "--no-deps",
      "--entrypoint",
      "node",
      "openclaw-gateway",
      "dist/index.js",
      "config",
      "get",
      "gateway.controlUi.allowedOrigins",
      "--json",
    ],
    {
      cwd: repoRoot,
      stdio: "pipe",
      encoding: "utf8",
    },
  );
  if (getResult.status === 0) {
    currentAllowedOrigins = (getResult.stdout || "").trim();
  }

  const mergedJson = mergeAllowedOriginsJson(
    currentAllowedOrigins,
    buildDesiredControlUiAllowedOrigins(),
  );
  const result = spawnSync(
    dockerCommand,
    [
      "compose",
      "run",
      "--rm",
      "--no-deps",
      "--entrypoint",
      "node",
      "openclaw-gateway",
      "dist/index.js",
      "config",
      "set",
      "gateway.controlUi.allowedOrigins",
      mergedJson,
      "--strict-json",
    ],
    {
      cwd: repoRoot,
      stdio: "pipe",
      encoding: "utf8",
    },
  );
  if (result.status !== 0) {
    process.stderr.write(
      [
        "WARN: failed to sync gateway.controlUi.allowedOrigins automatically; run this manually:",
        `  ${dockerCommand} compose run --rm --no-deps --entrypoint node openclaw-gateway dist/index.js config set gateway.controlUi.allowedOrigins '${mergedJson}' --strict-json`,
      ].join("\n") + "\n",
    );
    return false;
  }
  process.stdout.write(`Synced gateway.controlUi.allowedOrigins=${mergedJson}\n`);
  return true;
}

