// Run config CLI against the gateway image directly so setup does not depend on
// the long-lived openclaw-cli service sharing a running gateway namespace.
function runPrestartCli(args, options = {}) {
  return spawnSync(
    dockerCommand,
    [
      "compose",
      "run",
      "--rm",
      "--no-deps",
      "--entrypoint",
      "node",
      "openclaw-gateway",
      "dist/index.js",
      ...args,
    ],
    {
      cwd: repoRoot,
      stdio: "pipe",
      encoding: "utf8",
      ...options,
    },
  );
}

function buildCustomControlUi() {
  const result = spawnSync(process.execPath, [buildScriptPath], {
    cwd: repoRoot,
    stdio: "inherit",
  });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

function writeRootOverride() {
  const extraMounts = getExtraMounts();
  if (fs.existsSync(overridePath)) {
    const existing = fs.readFileSync(overridePath, "utf8");
    if (!LEGACY_GENERATED_MARKERS.some((marker) => existing.includes(marker))) {
      throw new Error(
        `Refusing to overwrite existing docker-compose.override.yml at ${overridePath} because it was not generated by this tool.`,
      );
    }
  }

  fs.writeFileSync(overridePath, buildOverrideContent(extraMounts), "utf8");
  return extraMounts;
}

