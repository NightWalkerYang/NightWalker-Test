#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../..");
const buildScriptPath = path.join(here, "build-custom-control-ui.mjs");
const overridePath = path.join(repoRoot, "docker-compose.override.yml");
const envFilePath = path.join(repoRoot, ".env");

const GENERATED_MARKER = "# Generated by tools/openclaw-control-ui-echarts setup tool";
const LEGACY_GENERATED_MARKERS = [
  GENERATED_MARKER,
  "# Generated by tools/openclaw-control-ui-echarts/setup-direct-docker-compose-up.mjs",
];
function readDotenvValue(key) {
  if (!fs.existsSync(envFilePath)) {
    return undefined;
  }

  const lines = fs.readFileSync(envFilePath, "utf8").split(/\r?\n/);
  for (const line of lines) {
    if (line.startsWith(`${key}=`)) {
      return line.slice(key.length + 1);
    }
  }
  return undefined;
}

function getExtraMounts() {
  const rawMounts = (
    process.env.OPENCLAW_EXTRA_MOUNTS ??
    readDotenvValue("OPENCLAW_EXTRA_MOUNTS") ??
    ""
  ).trim();
  if (!rawMounts) {
    return [];
  }

  if (/[\r\n\t]/.test(rawMounts)) {
    throw new Error("OPENCLAW_EXTRA_MOUNTS cannot contain control characters.");
  }

  return rawMounts
    .split(",")
    .map((mount) => mount.trim())
    .filter(Boolean)
    .map((mount) => {
      if (/\s/.test(mount)) {
        throw new Error("OPENCLAW_EXTRA_MOUNTS entries must not contain spaces.");
      }
      if (!mount.includes(":")) {
        throw new Error(`Invalid OPENCLAW_EXTRA_MOUNTS entry: ${mount}`);
      }
      return mount;
    });
}

function buildOverrideContent(extraMounts) {
  const lines = [
    GENERATED_MARKER,
    "services:",
    "  openclaw-gateway:",
    "    volumes:",
    "      - ./tools/openclaw-control-ui-echarts/generated/control-ui:/app/dist/control-ui:ro",
    "      - ${OPENCLAW_WORKSPACE_DIR}:/app/dist/control-ui/workspace-downloads:ro",
    "      - ${OPENCLAW_CONFIG_DIR}/workspace-agents:/app/dist/control-ui/workspace-agent-downloads:ro",
    "      - ./docs/reference/templates:/app/docs/reference/templates:ro",
  ];

  for (const mount of extraMounts) {
    lines.push(`      - ${mount}`);
  }

  lines.push(
    "  openclaw-tenant-platform:",
    "    image: ${OPENCLAW_IMAGE:-openclaw:local}",
    "    environment:",
    "      HOME: /home/node",
    "      OPENCLAW_CONFIG_DIR: /home/node/.openclaw",
    "      OPENCLAW_TENANT_PLATFORM_BIND: 0.0.0.0",
    "      OPENCLAW_TENANT_PLATFORM_PORT: 18801",
    "      OPENCLAW_TENANT_PLATFORM_API_BASE: /tenant-platform-api/v1",
    "      OPENCLAW_TENANT_PLATFORM_EDITION: ${OPENCLAW_TENANT_PLATFORM_EDITION:-cloud}",
    "      OPENCLAW_TENANT_PLATFORM_LICENSE_PATH: ${OPENCLAW_TENANT_PLATFORM_LICENSE_PATH:-}",
    "      OPENCLAW_TENANT_PLATFORM_LICENSE_PUBLIC_KEY: ${OPENCLAW_TENANT_PLATFORM_LICENSE_PUBLIC_KEY:-}",
    "      OPENCLAW_TENANT_PLATFORM_LICENSE_PUBLIC_KEY_PATH: ${OPENCLAW_TENANT_PLATFORM_LICENSE_PUBLIC_KEY_PATH:-}",
    "      TZ: ${OPENCLAW_TZ:-UTC}",
    "    volumes:",
    "      - ${OPENCLAW_CONFIG_DIR}:/home/node/.openclaw",
    "      - ./tools/openclaw-control-ui-echarts/sidecar:/app/tools/openclaw-control-ui-echarts/sidecar:ro",
    "    command:",
    "      [",
    "        \"node\",",
    "        \"tools/openclaw-control-ui-echarts/sidecar/tenant-platform/server.mjs\"",
    "      ]",
    "    ports:",
    "      - \"${OPENCLAW_TENANT_PLATFORM_PORT:-18801}:18801\"",
    "    healthcheck:",
    "      test:",
    "        [",
    "          \"CMD\",",
    "          \"node\",",
    "          \"-e\",",
    "          \"fetch('http://127.0.0.1:18801/healthz').then((response) => process.exit(response.ok ? 0 : 1)).catch(() => process.exit(1))\"",
    "        ]",
    "      interval: 15s",
    "      timeout: 5s",
    "      retries: 5",
    "      start_period: 10s",
    "    restart: unless-stopped",
  );

  if (extraMounts.length > 0) {
    lines.push("  openclaw-cli:");
    lines.push("    volumes:");
    for (const mount of extraMounts) {
      lines.push(`      - ${mount}`);
    }
  }

  return `${lines.join("\n")}\n`;
}

function buildCustomControlUi() {
  const result = spawnSync(process.execPath, [buildScriptPath], {
    cwd: repoRoot,
    stdio: "inherit",
  });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

function writeRootOverride() {
  const extraMounts = getExtraMounts();
  if (fs.existsSync(overridePath)) {
    const existing = fs.readFileSync(overridePath, "utf8");
    if (!LEGACY_GENERATED_MARKERS.some((marker) => existing.includes(marker))) {
      throw new Error(
        `Refusing to overwrite existing docker-compose.override.yml at ${overridePath} because it was not generated by this tool.`,
      );
    }
  }

  fs.writeFileSync(overridePath, buildOverrideContent(extraMounts), "utf8");
  return extraMounts;
}

function main() {
  buildCustomControlUi();
  const extraMounts = writeRootOverride();

  process.stdout.write(
    [
      `Wrote ${overridePath}`,
      ...(extraMounts.length > 0
        ? [`Included ${extraMounts.length} extra bind mount(s) from OPENCLAW_EXTRA_MOUNTS.`]
        : []),
      "You can now run `docker compose up -d` from the repo root and the custom Control UI will be mounted automatically.",
    ].join("\n"),
  );
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  process.stderr.write(`${message}\n`);
  process.exit(1);
}
