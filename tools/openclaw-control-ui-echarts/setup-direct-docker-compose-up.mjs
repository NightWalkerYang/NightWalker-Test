function isTruthyEnvValue(value) {
  return ["1", "true", "yes", "on"].includes(String(value ?? "").trim().toLowerCase());
}

function readDotenvValue(key) {
  if (!fs.existsSync(envFilePath)) {
    return undefined;
  }

  const lines = fs.readFileSync(envFilePath, "utf8").split(/\r?\n/);
  for (const line of lines) {
    if (line.startsWith(`${key}=`)) {
      return line.slice(key.length + 1);
    }
  }
  return undefined;
}

function ensureFileExists(filePath, label) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`${label} not found at ${filePath}`);
  }
}

function getExtraMounts() {
  const rawMounts = (
    process.env.OPENCLAW_EXTRA_MOUNTS ??
    readDotenvValue("OPENCLAW_EXTRA_MOUNTS") ??
    ""
  ).trim();
  if (!rawMounts) {
    return [];
  }

  if (/[\r\n\t]/.test(rawMounts)) {
    throw new Error("OPENCLAW_EXTRA_MOUNTS cannot contain control characters.");
  }

  return rawMounts
    .split(",")
    .map((mount) => mount.trim())
    .filter(Boolean)
    .map((mount) => {
      if (/\s/.test(mount)) {
        throw new Error("OPENCLAW_EXTRA_MOUNTS entries must not contain spaces.");
      }
      if (!mount.includes(":")) {
        throw new Error(`Invalid OPENCLAW_EXTRA_MOUNTS entry: ${mount}`);
      }
      return mount;
    });
}

function resolveGatewayPort() {
  return String(
    process.env.OPENCLAW_GATEWAY_PORT ?? readDotenvValue("OPENCLAW_GATEWAY_PORT") ?? "18789",
  ).trim();
}

function buildDesiredControlUiAllowedOrigins() {
  const port = resolveGatewayPort() || "18789";
  return [`http://127.0.0.1:${port}`, `http://localhost:${port}`];
}

function mergeAllowedOriginsJson(rawJson, desiredOrigins) {
  const existingOrigins = (() => {
    if (!rawJson) {
      return [];
    }
    try {
      const parsed = JSON.parse(rawJson);
      return Array.isArray(parsed) ? parsed : [];
    } catch {
      return [];
    }
  })();

  const merged = [];
  const seen = new Set();
  for (const origin of [...existingOrigins, ...desiredOrigins]) {
    if (typeof origin !== "string") {
      continue;
    }
    const normalized = origin.trim();
    if (!normalized || seen.has(normalized)) {
      continue;
    }
    merged.push(normalized);
    seen.add(normalized);
  }
  return JSON.stringify(merged);
}

function shouldSkipComposeUp() {
  return isTruthyEnvValue(
    process.env.OPENCLAW_SKIP_COMPOSE_UP ?? readDotenvValue("OPENCLAW_SKIP_COMPOSE_UP") ?? "",
  );
}

export function buildTenantPlatformExtraDependencySpecs() {
  return [...tenantPlatformRuntimePackageSpecs];
}

export function buildTenantPlatformPythonRuntimeDockerArgs(
  repoRootPath = repoRoot,
  imageRef = "openclaw:local",
) {
  const normalizedRepoRoot = String(repoRootPath || repoRoot).replace(/\\/g, "/");
  return [
    "run",
    "--rm",
    "-u",
    "0",
    "-v",
    `${normalizedRepoRoot}:/work`,
    "-w",
    "/work",
    imageRef,
    "sh",
    "-lc",
    "python3 -m pip --version >/dev/null 2>&1 || (apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends python3-pip python3-venv build-essential); python3 -m pip install --break-system-packages --no-cache-dir --prefer-binary --target /work/tools/openclaw-control-ui-echarts/generated/tenant-platform-runtime/python-packages -r /work/tools/openclaw-sandbox-simulation-starter/requirements.txt",
  ];
}

function ensureTenantPlatformRuntimeDir() {
  fs.mkdirSync(tenantPlatformRuntimeDir, { recursive: true });
  fs.mkdirSync(path.join(tenantPlatformRuntimeDir, "python-packages"), { recursive: true });
  fs.writeFileSync(
    path.join(tenantPlatformRuntimeDir, "package.json"),
    `${JSON.stringify(
      {
        name: "openclaw-tenant-platform-runtime",
        private: true,
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
}

function stageTenantPlatformRuntimeDependencies() {
  ensureTenantPlatformRuntimeDir();
  fs.rmSync(path.join(tenantPlatformRuntimeDir, "node_modules"), {
    recursive: true,
    force: true,
  });
  const result = spawnSync(
    npmCommand,
    [
      "install",
      "--omit=dev",
      "--ignore-scripts",
      "--no-fund",
      "--no-audit",
      "--no-package-lock",
      "--no-save",
      "--prefix",
      tenantPlatformRuntimeDir,
      ...buildTenantPlatformExtraDependencySpecs(),
    ],
    {
      cwd: repoRoot,
      stdio: "inherit",
    },
  );
  if (result.error) {
    throw new Error(`Failed to install tenant platform runtime dependencies: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error("Failed to install tenant platform runtime dependencies.");
  }
  ensureFileExists(
    path.join(tenantPlatformRuntimeDir, "node_modules", "pg", "package.json"),
    "Tenant platform pg runtime dependency",
  );
}

function stageTenantPlatformPythonRuntimeDependencies() {
  ensureTenantPlatformRuntimeDir();
  const pythonPackagesDir = path.join(tenantPlatformRuntimeDir, "python-packages");
  fs.rmSync(pythonPackagesDir, { recursive: true, force: true });
  fs.mkdirSync(pythonPackagesDir, { recursive: true });
  const requirementsPath = path.join(
    repoRoot,
    "tools",
    "openclaw-sandbox-simulation-starter",
    "requirements.txt",
  );
  ensureFileExists(requirementsPath, "Sandbox simulation Python requirements");
  const result = spawnSync(
    dockerCommand,
    buildTenantPlatformPythonRuntimeDockerArgs(repoRoot, process.env.OPENCLAW_IMAGE || "openclaw:local"),
    {
      cwd: repoRoot,
      stdio: "inherit",
    },
  );
  if (result.error) {
    throw new Error(`Failed to install tenant platform Python runtime dependencies: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error("Failed to install tenant platform Python runtime dependencies.");
  }
}

