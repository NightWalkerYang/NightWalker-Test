function syncPortableBaselineConfig() {
  const check = spawnSync(dockerCommand, ["compose", "config"], {
    cwd: repoRoot,
    stdio: "ignore",
  });
  if (check.status !== 0) {
    process.stderr.write(
      "WARN: docker compose is not available in repo root; skip syncing portable baseline config.\n",
    );
    return false;
  }

  const batchResult = spawnSync(
    process.execPath,
    [
      portableConfigScriptPath,
      "--source",
      portableConfigSourcePath,
      "--emit",
      "batch",
    ],
    {
      cwd: repoRoot,
      stdio: "pipe",
      encoding: "utf8",
    },
  );
  if (batchResult.status !== 0) {
    process.stderr.write(
      [
        `WARN: failed to derive portable baseline config from ${portableConfigSourcePath}; skip syncing.`,
        batchResult.stderr?.trim(),
      ]
        .filter(Boolean)
        .join("\n") + "\n",
    );
    return false;
  }

  const batchJson = (batchResult.stdout || "").trim();
  if (!batchJson) {
    return false;
  }

  const result = runPrestartCli(["config", "set", "--batch-json", batchJson]);
  if (result.status !== 0) {
    process.stderr.write(
      [
        "WARN: failed to sync portable baseline config automatically; run this manually:",
        "  docker compose run --rm --no-deps openclaw-cli config set --batch-json '<portable batch JSON>'",
        result.stderr?.trim(),
      ]
        .filter(Boolean)
        .join("\n") + "\n",
    );
    return false;
  }
  process.stdout.write("Synced portable baseline config from openclaw.local.example.json5\n");
  return true;
}

function runTargetedComposeUp() {
  if (shouldSkipComposeUp()) {
    process.stdout.write("Skipped docker compose up because OPENCLAW_SKIP_COMPOSE_UP=1\n");
    return false;
  }

  const check = spawnSync(dockerCommand, ["compose", "config"], {
    cwd: repoRoot,
    stdio: "ignore",
  });
  if (check.status !== 0) {
    throw new Error(
      "docker compose is not available in repo root; cannot apply the zero-intrusive deployment.",
    );
  }

  const result = spawnSync(
    dockerCommand,
    ["compose", "up", "-d", "--force-recreate", ...COMPOSE_UP_SERVICES],
    {
      cwd: repoRoot,
      stdio: "inherit",
    },
  );
  if (result.status !== 0) {
    throw new Error(
      `${dockerCommand} compose up failed for ${COMPOSE_UP_SERVICES.join(", ")}.`,
    );
  }

  process.stdout.write(
    `Applied docker compose up --force-recreate for ${COMPOSE_UP_SERVICES.join(", ")}\n`,
  );
  return true;
}

function main() {
  buildCustomControlUi();
  stageTenantPlatformRuntimeDependencies();
  stageTenantPlatformPythonRuntimeDependencies();
  const extraMounts = writeRootOverride();
  syncPortableBaselineConfig();
  syncGatewayControlUiRoot();
  syncControlUiAllowedOrigins();
  syncControlUiHostHeaderOriginFallbackDisabled();
  syncControlUiDeviceAuthBypass();
  const composeUpApplied = runTargetedComposeUp();

  process.stdout.write(
    [
      `Wrote ${overridePath}`,
      ...(extraMounts.length > 0
        ? [`Included ${extraMounts.length} extra bind mount(s) from OPENCLAW_EXTRA_MOUNTS.`]
        : []),
      composeUpApplied
        ? "Applied the zero-intrusive docker compose deployment for the related services."
        : "Skipped docker compose up; run `docker compose up -d --force-recreate openclaw-gateway openclaw-tenant-platform openclaw-gateway-proxy` when you want to apply the deployment.",
    ].join("\n"),
  );
}

const isEntrypoint =
  !!process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isEntrypoint) {
  try {
    main();
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`${message}\n`);
    process.exit(1);
  }
}
