function isTruthyEnvValue(value) {
  return ["1", "true", "yes", "on"].includes(String(value ?? "").trim().toLowerCase());
}

function readDotenvValue(key) {
  if (!fs.existsSync(envFilePath)) {
    return undefined;
  }

  const lines = fs.readFileSync(envFilePath, "utf8").split(/\r?\n/);
  for (const line of lines) {
    if (line.startsWith(`${key}=`)) {
      return line.slice(key.length + 1);
    }
  }
  return undefined;
}

function getExtraMounts() {
  const rawMounts = (
    process.env.OPENCLAW_EXTRA_MOUNTS ??
    readDotenvValue("OPENCLAW_EXTRA_MOUNTS") ??
    ""
  ).trim();
  if (!rawMounts) {
    return [];
  }

  if (/[\r\n\t]/.test(rawMounts)) {
    throw new Error("OPENCLAW_EXTRA_MOUNTS cannot contain control characters.");
  }

  return rawMounts
    .split(",")
    .map((mount) => mount.trim())
    .filter(Boolean)
    .map((mount) => {
      if (/\s/.test(mount)) {
        throw new Error("OPENCLAW_EXTRA_MOUNTS entries must not contain spaces.");
      }
      if (!mount.includes(":")) {
        throw new Error(`Invalid OPENCLAW_EXTRA_MOUNTS entry: ${mount}`);
      }
      return mount;
    });
}

function resolveGatewayPort() {
  return String(
    process.env.OPENCLAW_GATEWAY_PORT ?? readDotenvValue("OPENCLAW_GATEWAY_PORT") ?? "18789",
  ).trim();
}

function resolveOpenclawConfigDir() {
  return String(
    process.env.OPENCLAW_CONFIG_DIR ?? readDotenvValue("OPENCLAW_CONFIG_DIR") ?? path.join(
      process.env.HOME ?? process.env.USERPROFILE ?? repoRoot,
      ".openclaw",
    ),
  ).trim();
}

function buildDesiredControlUiAllowedOrigins() {
  const port = resolveGatewayPort() || "18789";
  return [`http://127.0.0.1:${port}`, `http://localhost:${port}`];
}

function mergeAllowedOriginsJson(rawJson, desiredOrigins) {
  const existingOrigins = (() => {
    if (!rawJson) {
      return [];
    }
    try {
      const parsed = JSON.parse(rawJson);
      return Array.isArray(parsed) ? parsed : [];
    } catch {
      return [];
    }
  })();

  const merged = [];
  const seen = new Set();
  for (const origin of [...existingOrigins, ...desiredOrigins]) {
    if (typeof origin !== "string") {
      continue;
    }
    const normalized = origin.trim();
    if (!normalized || seen.has(normalized)) {
      continue;
    }
    merged.push(normalized);
    seen.add(normalized);
  }
  return JSON.stringify(merged);
}

function shouldSkipComposeUp() {
  return isTruthyEnvValue(
    process.env.OPENCLAW_SKIP_COMPOSE_UP ?? readDotenvValue("OPENCLAW_SKIP_COMPOSE_UP") ?? "",
  );
}

