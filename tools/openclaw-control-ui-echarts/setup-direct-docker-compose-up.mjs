function walkFiles(rootDir) {
  const entries = fs.readdirSync(rootDir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(rootDir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkFiles(fullPath));
      continue;
    }
    if (entry.isFile()) {
      files.push(fullPath);
    }
  }
  return files;
}

function syncWorkspaceOverlayTree(overlayRoot, workspaceDir) {
  fs.mkdirSync(workspaceDir, { recursive: true });
  for (const sourceFile of walkFiles(overlayRoot)) {
    const relativePath = path.relative(overlayRoot, sourceFile);
    const destinationFile = path.join(workspaceDir, relativePath);
    fs.mkdirSync(path.dirname(destinationFile), { recursive: true });
    fs.copyFileSync(sourceFile, destinationFile);
    const mode = fs.statSync(sourceFile).mode;
    fs.chmodSync(destinationFile, mode);
  }
}

function syncWorkspaceOverlays() {
  if (!fs.existsSync(workspaceOverlayPath)) {
    return 0;
  }

  const workspaceRoot = path.join(resolveOpenclawConfigDir(), "workspace-agents");
  fs.mkdirSync(workspaceRoot, { recursive: true });
  const names = fs
    .readdirSync(workspaceRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter(
      (name) => name === "kingdee-cloud" || /^tenant-.*-kingdee-cloud-.*$/.test(name),
    )
    .sort();

  const targets = names.length > 0 ? names : ["kingdee-cloud"];
  for (const name of targets) {
    syncWorkspaceOverlayTree(workspaceOverlayPath, path.join(workspaceRoot, name));
  }
  process.stdout.write(
    `Synced kingdee-cloud workspace overlay to ${targets.length} workspace(s) under ${workspaceRoot}\n`,
  );
  return targets.length;
}

function runTargetedComposeUp() {
  if (shouldSkipComposeUp()) {
    process.stdout.write("Skipped docker compose up because OPENCLAW_SKIP_COMPOSE_UP=1\n");
    return false;
  }

  const check = spawnSync(dockerCommand, ["compose", "config"], {
    cwd: repoRoot,
    stdio: "ignore",
  });
  if (check.status !== 0) {
    throw new Error(
      "docker compose is not available in repo root; cannot apply the zero-intrusive deployment.",
    );
  }

  const result = spawnSync(
    dockerCommand,
    ["compose", "up", "-d", "--force-recreate", ...COMPOSE_UP_SERVICES],
    {
      cwd: repoRoot,
      stdio: "inherit",
    },
  );
  if (result.status !== 0) {
    throw new Error(
      `${dockerCommand} compose up failed for ${COMPOSE_UP_SERVICES.join(", ")}.`,
    );
  }

  process.stdout.write(
    `Applied docker compose up --force-recreate for ${COMPOSE_UP_SERVICES.join(", ")}\n`,
  );
  return true;
}

function main() {
  buildCustomControlUi();
  const extraMounts = writeRootOverride();
  syncWorkspaceOverlays();
  syncPortableBaselineConfig();
  syncTenantMemberBootstrapHookConfig();
  syncGatewayControlUiRoot();
  syncControlUiAllowedOrigins();
  syncControlUiHostHeaderOriginFallbackDisabled();
  syncControlUiDeviceAuthBypass();
  const composeUpApplied = runTargetedComposeUp();

  process.stdout.write(
    [
      `Wrote ${overridePath}`,
      ...(extraMounts.length > 0
        ? [`Included ${extraMounts.length} extra bind mount(s) from OPENCLAW_EXTRA_MOUNTS.`]
        : []),
      composeUpApplied
        ? "Applied the zero-intrusive docker compose deployment for the related services."
        : "Skipped docker compose up; run `docker compose up -d --force-recreate openclaw-gateway openclaw-tenant-platform openclaw-gateway-proxy` when you want to apply the deployment.",
    ].join("\n"),
  );
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  process.stderr.write(`${message}\n`);
  process.exit(1);
}
