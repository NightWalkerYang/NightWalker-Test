function isTruthyEnvValue(value) {
  return ["1", "true", "yes", "on"].includes(
    String(value ?? "")
      .trim()
      .toLowerCase(),
  );
}

function readDotenvValue(key) {
  if (!fs.existsSync(envFilePath)) {
    return undefined;
  }

  const lines = fs.readFileSync(envFilePath, "utf8").split(/\r?\n/);
  for (const line of lines) {
    if (line.startsWith(`${key}=`)) {
      return line.slice(key.length + 1);
    }
  }
  return undefined;
}

function getExtraMounts() {
  const rawMounts = (
    process.env.OPENCLAW_EXTRA_MOUNTS ??
    readDotenvValue("OPENCLAW_EXTRA_MOUNTS") ??
    ""
  ).trim();
  if (!rawMounts) {
    return [];
  }

  if (/[\r\n\t]/.test(rawMounts)) {
    throw new Error("OPENCLAW_EXTRA_MOUNTS cannot contain control characters.");
  }

  return rawMounts
    .split(",")
    .map((mount) => mount.trim())
    .filter(Boolean)
    .map((mount) => {
      if (/\s/.test(mount)) {
        throw new Error("OPENCLAW_EXTRA_MOUNTS entries must not contain spaces.");
      }
      if (!mount.includes(":")) {
        throw new Error(`Invalid OPENCLAW_EXTRA_MOUNTS entry: ${mount}`);
      }
      return mount;
    });
}

